{#
  Generated by ingen_fab (`ingen_fab dbt profile`, `ingen_fab dbt <verb>`, `ingen_fab dbt
  orchestrator` refresh it): do not edit, it is overwritten.

  Run logging into the log store, by dbt itself, from an on-run-end hook:

      on-run-end:
        - "{{ ingen_fab_log_run(results) }}"

  Two tables, the ones the Spark adapter's projects have always had:
    dbt_batch          one row per dbt invocation (batch_id = invocation_id)
    dbt_execution_log  one row per model, test, seed and snapshot of that invocation

  Where they live:
    dbt-fabricspark (lakehouse projects): the log lakehouse, var `log_lakehouse` (lh_log)
    dbt-fabric (warehouse projects):      the log warehouse, var `log_warehouse` (wh_log),
                                          schema var `log_schema` (dbo)
  When the workspace has no store of that name, the run is logged into the project's own
  lakehouse or warehouse instead, with a line in dbt's output saying so (the fallback the
  Spark adapter's notebooks had).
  The orchestrator notebook passes both vars; from a machine, set them with --vars or in
  dbt_project.yml. `ingen_fab_runner` names who ran dbt (cli, or notebook/<name>).
#}

{% macro ingen_fab_log_run(results) %}
    {# dbt runs this hook after build, run, test, seed and snapshot when at least one node was
       selected; a selection of nothing, compile and parse run no hook, so they leave no row #}
    {% if execute %}
        {% if target.type == 'fabricspark' %}
            {{ ingen_fab_log_run_spark(results) }}
        {% elif target.type == 'fabric' %}
            {{ ingen_fab_log_run_warehouse(results) }}
        {% else %}
            {{ log("ingen_fab logging: no log store for adapter " ~ target.type ~ "; run not logged", info=True) }}
        {% endif %}
    {% endif %}
{% endmacro %}


