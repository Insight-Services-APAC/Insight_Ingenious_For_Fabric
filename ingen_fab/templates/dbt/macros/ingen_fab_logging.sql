{% macro ingen_fab_sql_string(value, backslashes=false, max_length=4000) %}
    {#- Spark SQL reads a backslash in a string literal as an escape (a message ending in `\`
        before the closing quote breaks the statement), T-SQL does not: double it for Spark -#}
    {%- if value is none -%}NULL{%- else -%}
        {%- set text = (value | string)[:max_length] -%}
        {%- if backslashes -%}{%- set text = text | replace("\\", "\\\\") -%}{%- endif -%}
        '{{ text | replace("'", "''") }}'
    {%- endif -%}
{% endmacro %}

{% macro ingen_fab_timestamp(value, sql_type) %}
    {%- if value is none -%}NULL{%- else -%}CAST('{{ value.strftime('%Y-%m-%d %H:%M:%S') }}' AS {{ sql_type }}){%- endif -%}
{% endmacro %}

{% macro ingen_fab_node_rows(results) %}
    {%- set rows = [] -%}
    {%- for result in results -%}
        {#- a Jinja `set` inside a loop stays in the loop: the namespace carries the timing out -#}
        {%- set ns = namespace(started=none, ended=none) -%}
        {%- for t in result.timing -%}
            {%- if t.name == 'execute' or (t.name == 'compile' and ns.started is none) -%}
                {%- set ns.started = t.started_at -%}
                {%- set ns.ended = t.completed_at -%}
            {%- endif -%}
        {%- endfor -%}
        {%- do rows.append({
            'unique_id': result.node.unique_id,
            'resource_type': result.node.resource_type,
            'name': result.node.name,
            'status': result.status | string,
            'message': result.message,
            'execution_time': result.execution_time or 0,
            'started_at': ns.started,
            'ended_at': ns.ended,
            'failures': result.failures or 0,
        }) -%}
    {%- endfor -%}
    {{ return(rows) }}
{% endmacro %}

{% macro ingen_fab_batch_row(results) %}
    {%- set statuses = results | map(attribute='status') | map('string') | list -%}
    {%- set selector = invocation_args_dict.get('select') if invocation_args_dict is defined else none -%}
    {%- if selector is iterable and selector is not string -%}{%- set selector = selector | join(' ') -%}{%- endif -%}
    {%- set errors = statuses | select('in', ['error', 'fail']) | list | length -%}
    {{ return({
        'batch_id': invocation_id,
        'project_name': project_name,
        'target_name': target.name,
        'target_type': target.type,
        'command': flags.WHICH,
        'selector': selector,
        'runner': var('ingen_fab_runner', 'cli'),
        'started_at': run_started_at,
        'ended_at': modules.datetime.datetime.utcnow(),
        'status': 'error' if errors > 0 else 'success',
        'total_nodes': statuses | length,
        'success_count': statuses | select('in', ['success', 'pass']) | list | length,
        'error_count': statuses | select('equalto', 'error') | list | length,
        'fail_count': statuses | select('equalto', 'fail') | list | length,
        'skipped_count': statuses | select('equalto', 'skipped') | list | length,
        'warn_count': statuses | select('equalto', 'warn') | list | length,
    }) }}
{% endmacro %}

{% macro ingen_fab_node_values(rows, batch_id, ts_type, bs=false) %}
    {%- for r in rows -%}
        ({{ ingen_fab_sql_string(batch_id, bs) }}, {{ ingen_fab_sql_string(r.unique_id, bs) }}, {{ ingen_fab_sql_string(r.resource_type, bs) }}, {{ ingen_fab_sql_string(r.name, bs) }}, {{ ingen_fab_sql_string(r.status, bs) }}, {{ ingen_fab_sql_string(r.message, bs) }}, {{ r.execution_time }}, {{ ingen_fab_timestamp(r.started_at, ts_type) }}, {{ ingen_fab_timestamp(r.ended_at, ts_type) }}, {{ r.failures }}){{ ", " if not loop.last }}
    {%- endfor -%}
{% endmacro %}

{% macro ingen_fab_batch_values(b, ts_type, bs=false) %}
    ({{ ingen_fab_sql_string(b.batch_id, bs) }}, {{ ingen_fab_sql_string(b.project_name, bs) }}, {{ ingen_fab_sql_string(b.target_name, bs) }}, {{ ingen_fab_sql_string(b.target_type, bs) }}, {{ ingen_fab_sql_string(b.command, bs) }}, {{ ingen_fab_sql_string(b.selector, bs) }}, {{ ingen_fab_sql_string(b.runner, bs) }}, {{ ingen_fab_timestamp(b.started_at, ts_type) }}, {{ ingen_fab_timestamp(b.ended_at, ts_type) }}, {{ ingen_fab_sql_string(b.status, bs) }}, {{ b.total_nodes }}, {{ b.success_count }}, {{ b.error_count }}, {{ b.fail_count }}, {{ b.skipped_count }}, {{ b.warn_count }})
{% endmacro %}


